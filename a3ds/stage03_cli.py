"""Stage 03 end-to-end demo and reproducible reference silhouette fitting.

No external engine or Python library dependency. Input masks must already be
binary, calibrated and aligned, NOT an unprocessed perspective illustration.
The 'fixture' subcommand generates synthetic known-geometry test reference data;
the 'fit' subcommand NEVER receives those ground-truth fitting parameters.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

from .camera import standard_views
from .fit_geometry import ShapeParams, alter_project
from .glb import write_glb
from .optimizer import SilhouetteReference, fit
from .png import write_png
from .project import SurfaceProject, demo_project
from .raster import render_mesh, render_silhouette
from .silhouette import BinaryMask, write_difference_png


def _synthetic(out: Path, project: SurfaceProject, width: int, height: int) -> None:
    truth = ShapeParams(width_scale=1.21, height_scale=1.13,
                        nose_extension=0.39, nose_tip_scale=1.00,
                        rear_tip_scale=1.00)
    truth_project = alter_project(project, truth)
    cameras = standard_views(width, height)
    out.mkdir(parents=True, exist_ok=True)
    info = {
        "format": "a3ds.synthetic-silhouette-fixture/1",
        "warning": "SYNTHETIC reference generated by A3DS itself; NOT a user sketch",
        "truth": truth.to_dict(),
        "views": {}
    }
    for name in ("side", "top", "front", "rear"):
        image = render_silhouette(truth_project.build(), cameras[name])
        mask = BinaryMask.from_render(image)
        mask.save_png(out / f"{name}_reference.png")
        info["views"][name] = {
            "file": f"{name}_reference.png", "target_area": mask.area,
            "calibration": "A3DS standard camera, fixed BU scale; no auto image detection"
        }
    (out / "fixture.json").write_text(
        json.dumps(info, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def _references(args) -> list[SilhouetteReference]:
    if not args.ref:
        raise ValueError("Need at least one explicit --ref NAME=mask.png")
    cameras = standard_views(args.width, args.height)
    references: list[SilhouetteReference] = []
    for binding in args.ref:
        if "=" not in binding:
            raise ValueError(f"Missing NAME=PATH in reference: {binding}")
        name, path = binding.split("=", 1)
        if name not in ("side", "top", "front", "rear"):
            raise ValueError(f"Unknown orthographic view {name}")
        target = BinaryMask.read_png(path)
        if target.width != args.width or target.height != args.height:
            raise ValueError(f"{name} reference size does not match --width/--height")
        references.append(SilhouetteReference(name, cameras[name], target))
    return references


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="A3DS Stage 03 constrained silhouette fitting")
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("fixture", "fit"):
        cmd = sub.add_parser(name)
        cmd.add_argument("--project", help="Original Stage 01 .a3ds.json; default demo")
        cmd.add_argument("--out-dir", required=True)
        cmd.add_argument("--width", type=int, default=160)
        cmd.add_argument("--height", type=int, default=120)
        if name == "fit":
            cmd.add_argument("--ref", action="append", help="Explicit view=reference.png")
            cmd.add_argument("--active", nargs="+", default=[
                "width_scale", "height_scale", "nose_extension"
            ])
            cmd.add_argument("--max-passes", type=int, default=12)
            cmd.add_argument("--min-iou", type=float, default=0.90)
    args = parser.parse_args(argv)
    out = Path(args.out_dir)
    project = SurfaceProject.load(args.project) if args.project else demo_project()
    if args.command == "fixture":
        _synthetic(out, project, args.width, args.height)
        print("Synthetic calibrated masks saved to", out)
        return 0

    references = _references(args)
    result = fit(
        project, references, active=args.active,
        max_passes=args.max_passes, min_iou_per_view=args.min_iou
    )
    out.mkdir(parents=True, exist_ok=True)
    optimized_project = alter_project(project, result.parameters)
    optimized_project.save(out / "fitted.a3ds.json")
    mesh = optimized_project.build()
    write_glb(mesh, out / "fitted.glb")
    # Build per-view model raster and a red/blue reference disagreement map.
    for reference in references:
        camera, name = reference.camera, reference.name
        color = render_mesh(mesh, camera)
        color.save(out / f"{name}_fitted.png")
        pred = BinaryMask.from_render(render_silhouette(mesh, camera))
        pred.save_png(out / f"{name}_fitted_mask.png")
        write_difference_png(out / f"{name}_difference.png", pred, reference.target)
    (out / "fit_report.json").write_text(
        json.dumps(result.to_dict(), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8"
    )
    print(json.dumps(result.to_dict(), indent=2, ensure_ascii=False))
    # A high residual is NOT silently ignored. Keep the files for inspection.
    return 0 if result.status == "WITHIN_TOLERANCE" else 3


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, RuntimeError, KeyError, TypeError) as exc:
        print(f"A3DS Stage 03: {exc}", file=sys.stderr)
        sys.exit(2)
